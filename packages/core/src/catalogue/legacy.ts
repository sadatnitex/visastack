/**
 * A frozen copy of the 81 fields that are live today in apps/web/src/lib/profile-fields.ts.
 *
 * Why it exists: field definitions are registered lazily and the first writer wins, so a key, pack,
 * protection level or type that changes in code after a value is stored silently disagrees with the
 * database. A web test compares the live registry with this copy field by field, so any change to a
 * live field fails until this copy is changed on purpose, with a reason recorded in
 * docs/product/master-profile-enrichment/HANDOFF.md.
 *
 * Labels are included because they are what people see; the planned Title Case change for these 81
 * labels is a separate, previewed change and must update this copy in the same commit.
 *
 * "layer" is presentation only and is not part of the frozen identity.
 */
export interface LegacyFieldSnapshot {
  readonly key: string;
  readonly label: string;
  readonly sensitivity: 'STANDARD' | 'SENSITIVE' | 'RESTRICTED';
  readonly pack: ProfilePack;
  readonly type: 'text' | 'date';
  readonly group?: string;
  readonly groupLabel?: string;
  readonly options?: readonly string[];
  readonly layer: LayerKey;
  /** The catalogue field that holds the text when this choice is set to Other. Not part of the frozen identity. */
  readonly otherDetailKey?: string;
}

