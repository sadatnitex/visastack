import type { CatalogueModule } from './types';

/**
 * The opt-in sections of the profile.
 *
 * How a person experiences it: every section is visible, but only the common ones are open from the
 * start. The rest are locked until the person ticks them. Opening a section makes its fields
 * count toward the completion percentage at once; leaving it locked costs nothing. A section that
 * already holds a saved value is always open, so nothing entered is ever hidden.
 *
 * How it is built: a module lists blocks of the field catalogue ("S:<section>" for single fields,
 * "G:<record>" for a repeating record) and, for the sections that exist today, the live fields and
 * records. Default-open modules hold ONLY live fields, so the completion figure for a person who
 * has opened nothing is exactly the live fields that are common to everyone. Extra detail for a
 * default-open section is its own locked module ("extends"), so it can be opened separately.
 */
type ModuleInput = Omit<CatalogueModule, 'defaultOpen'> & { readonly defaultOpen?: boolean };
const m = (input: ModuleInput): CatalogueModule => ({ defaultOpen: false, ...input });

