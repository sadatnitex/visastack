import type { CatalogueDocument } from './types';

/**
 * The curated document catalogue.
 *
 * Built from the other product's two document lists (114 stored types and 137 scanner types) with
 * exact duplicates merged into one entry and listed as aliases, plus a small set of types added from
 * the owner's enrichment areas (origin "proposed", pending adviser sign-off). Unlike the other
 * product, which folds many distinct documents into a nearby type (for example a fixed deposit
 * receipt becomes a bank statement), distinct documents stay distinct here, because
 * documents.docType is free text and nothing forces a lossy fold. Raw biometric data is left out on
 * purpose: only the receipt for a biometric appointment is a document.
 *
 * "pack" is the intended sharing category. It is NOT live: today only Passport, Bank Statement and
 * Employment Certificate have a category (packages/services/src/sharing.ts), and every other type is
 * invisible to category grants. Phase 2 must review each pack before deriving that mapping, because
 * doing so makes these documents reachable by grants that include the pack.
 */
type DocumentInput = Omit<CatalogueDocument, 'recognisedToday'> & {
  readonly recognisedToday?: boolean;
};

const doc = (input: DocumentInput): CatalogueDocument => ({
  ...input,
  recognisedToday: input.recognisedToday ?? false,
});

