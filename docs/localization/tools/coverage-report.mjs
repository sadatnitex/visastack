const csvRows = (file) => {
  const t = fs.readFileSync(file, 'utf8');
  const out = [];
  let row = [];
  let fld = '';
  let qt = false;
  for (let i = 0; i < t.length; i++) {
    const ch = t[i];
    if (qt) {
      if (ch === '"') {
        if (t[i + 1] === '"') {
          fld += '"';
          i++;
        } else qt = false;
      } else fld += ch;
    } else if (ch === '"') qt = true;
    else if (ch === ',') {
      row.push(fld);
      fld = '';
    } else if (ch === '\n') {
      row.push(fld);
      out.push(row);
      row = [];
      fld = '';
    } else if (ch !== '\r') fld += ch;
  }
  const [h, ...body] = out;
  return body
    .filter((r) => r.length === h.length)
    .map((r) => Object.fromEntries(h.map((k, i) => [k, r[i]])));
};
