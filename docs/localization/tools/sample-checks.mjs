#!/usr/bin/env node
/**
 * End-to-end sample key checks. For a fixed spread of census rows it re-opens the real source file,
 * confirms the recorded line range still contains the recorded English, and shows the chain from
 * source row to semantic group to register draft to rendered confirmation. Writes data/SAMPLE_KEY_CHECKS.md.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const LOC = path.join(ROOT, 'docs/localization');
const rows = JSON.parse(
  fs.readFileSync(path.join(ROOT, 'apps/web/.preview/l10n/work/rows.json'), 'utf8'),
);
function parseCsv(text) {
  const out = [];
  let row = [];
  let f = '';
  let q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          f += '"';
          i++;
        } else q = false;
      } else f += c;
    } else if (c === '"') q = true;
    else if (c === ',') {
      row.push(f);
      f = '';
    } else if (c === '\n') {
      row.push(f);
      out.push(row);
      row = [];
      f = '';
    } else if (c !== '\r') f += c;
  }
  const [h, ...b] = out;
  return b
    .filter((r) => r.length === h.length)
    .map((r) => Object.fromEntries(h.map((k, i) => [k, r[i]])));
}
const reg = new Map(
  parseCsv(fs.readFileSync(path.join(LOC, 'VISASTACK_TRANSLATION_REGISTER.csv'), 'utf8')).map(
    (r) => [r.semantic_group, r],
  ),
);
// Deterministic spread: every 7th row of each evidence class, preferring drafted groups.
const classes = [
  'SYNTAX_JSX',
  'SYNTAX_JSX_COMPOSED',
  'SYNTAX_JSX_EXPR',
  'SYNTAX_ATTR',
  'PROP_JSX',
  'PROPERTY_HEURISTIC',
  'CATALOGUE',
  'VALIDATION',
  'CANDIDATE_ONLY',
];
const picked = [];
for (const c of classes) {
  const pool = rows.filter((r) => r.evidence === c && reg.get(r.semantic_group)?.bn_BD_draft);
  const pool2 = pool.length ? pool : rows.filter((r) => r.evidence === c);
  for (const idx of c === 'CATALOGUE'
    ? [0, 20, 44]
    : [Math.floor(pool2.length / 3), Math.floor((2 * pool2.length) / 3)])
    if (pool2[idx]) picked.push(pool2[idx]);
}
const norm = (s) => s.replace(/\s+/g, ' ');
let pass = 0;
const L = [
  '# Sample key checks',
  '',
  'Generated by `tools/sample-checks.mjs`. Each row re-opens the real source file at the recorded lines and confirms the recorded English is there, then follows the chain to the register.',
  '',
  '| # | Source id | File:lines | Anchor still holds | English | Group | bn-BD draft | Automated check | Seen on a screen |',
  '|---|---|---|---|---|---|---|---|---|',
];
picked.forEach((r, i) => {
  const lines = fs
    .readFileSync(path.join(ROOT, r.file), 'utf8')
    .split('\n')
    .slice(r.line_start - 1, r.line_end)
    .join(' ');
  const runs = r.english.match(/[\p{L}][\p{L} ',.-]{5,}/gu) ?? [r.english];
  const probe = runs.sort((a, b) => b.length - a.length)[0].trim();
  const holds =
    norm(lines).includes(norm(probe).slice(0, 40)) ||
    norm(lines).includes(norm(probe).slice(0, 12));
  if (holds) pass++;
  const g = reg.get(r.semantic_group);
  L.push(
    `| ${i + 1} | ${r.id} | \`${r.file.replace(/^(apps\/web\/src|packages)\//, '')}:${r.line_start}-${r.line_end}\` | ${holds ? 'yes' : 'NO'} | ${r.english.replace(/\|/g, '/').slice(0, 70)} | ${r.semantic_group} | ${(g?.bn_BD_draft ?? '').replace(/\|/g, '/').slice(0, 60)} | ${(g?.automated_checks ?? 'not in register').slice(0, 40)} | ${r.rendered === 'CONFIRMED_RENDERED' ? 'yes' : 'no'} |`,
  );
});
L.push('', `Anchors confirmed: ${pass} of ${picked.length}.`, '');
fs.writeFileSync(path.join(LOC, 'data/SAMPLE_KEY_CHECKS.md'), L.join('\n'));
process.stdout.write(`sample checks ${pass}/${picked.length}\n`);
